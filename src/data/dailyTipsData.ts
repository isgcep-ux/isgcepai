/**
 * Returns today's designated tip using day-of-year hashing,
 * guaranteeing a deterministic tip for each day of the year.
 */
export const getTodayTip = (): DailyTipItem => {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear) % DAILY_TIPS_DATA.length;
  return DAILY_TIPS_DATA[index];
};

/**
 * Returns a random tip different from current ID
 */
export const getRandomTip = (currentId?: string): DailyTipItem => {
  const pool = currentId
    ? DAILY_TIPS_DATA.filter((t) => t.id !== currentId)
    : DAILY_TIPS_DATA;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex] || DAILY_TIPS_DATA[0];
};
